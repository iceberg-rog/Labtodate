export function defaultOptions(kind: DocKind): DocOptions {
  if (kind === 'QUOTE') {
    const raw = parseInt(process.env.PROFORMA_VALID_DAYS ?? '', 10);
    const days = Number.isFinite(raw) && raw >= 1 && raw <= 365 ? raw : 14;
    return { showLogo: true, showSignature: true, showCustomerNo: false, showBankDetails: true, showGreeting: true, days };
  }
  if (kind === 'INVOICE') {
    return { showLogo: true, showSignature: false, showCustomerNo: false, showBankDetails: true, showGreeting: false, days: 5 };
  }
  return { showLogo: true, showSignature: false, showCustomerNo: false, showBankDetails: false, showGreeting: true, days: 0 };
}

